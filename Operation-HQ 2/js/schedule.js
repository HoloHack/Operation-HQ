  // --- Alt-week logic ---

  mondayOf(date) {
    const d = new Date(date);
    const day = d.getDay(); // 0=Sun..6=Sat
    const diff = day === 0 ? -6 : 1 - day; // days to subtract to reach Monday
    d.setDate(d.getDate() + diff);
    d.setHours(0, 0, 0, 0);
    return d;
  },

  isAltWeek(profile, forDate) {
    if (profile.altWeekOverride === true) return true;
    if (profile.altWeekOverride === false) return false;
    if (!profile.altAnchorDate || !profile.altIntervalWeeks) return false;
    const anchorMonday = this.mondayOf(profile.altAnchorDate + "T00:00:00");
    const thisMonday = this.mondayOf(forDate || new Date());
    const weeksDiff = Math.round((thisMonday - anchorMonday) / (7 * 86400000));
    return weeksDiff >= 0 && weeksDiff % profile.altIntervalWeeks === 0;
  },

  activePhase(profile = this.active, forDate = new Date()) {
    if (!profile?.phases?.length) return null;
    const key = hqLocalDateKey(forDate);
    return profile.phases.find(phase => key >= phase.start && key <= phase.end) || null;
  },

  isFlexibleBlock(block) {
    return /flex|study|coding|business|catch-up|practice|competition/i.test(`${block?.t || ""} ${block?.d || ""}`);
  },

  phaseLabelForBlock(block, phase) {
    if (!phase || !this.isFlexibleBlock(block)) return null;
    if (phase.mode === "wharton") return "Wharton priority";
    if (phase.mode === "backlog") return Number(block.s?.slice(0, 2)) < 12 ? "Tuition backlog" : "Tuition backlog + client outreach";
    if (phase.mode === "trial") return "Competition trial practice";
    if (phase.mode === "steady") return "Competition / maths / study rotation";
    return null;
  },

  // The blocks actually in effect for a given day-of-week key right now,
  // accounting for the alt-week rule if this profile and day have one.
  blocksFor(profile, dayKey, forDate = new Date()) {
    const usesAlt = profile.altDays && profile.altDays[dayKey] && this.isAltWeek(profile, forDate);
    const base = usesAlt ? profile.altDays[dayKey] : (profile.days[dayKey] || []);
    const phase = this.activePhase(profile, forDate);
    return base.map(block => {
      const phasePriority = this.phaseLabelForBlock(block, phase);
      return phasePriority ? { ...block, phasePriority, d: [block.d, `v8 priority: ${phasePriority}`].filter(Boolean).join(" · ") } : block;
    });
  },

  dayHasAlt(profile, dayKey) {
    return !!(profile.altDays && profile.altDays[dayKey]);
  },

