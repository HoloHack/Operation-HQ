  // Cheap re-highlight of which block is "now" — called every minute
  // without touching anything else, so it never interrupts an in-progress
  // edit in the day editor below it.
  renderTodayHighlightOnly() {
    const profile = this.active;
    if (!profile) return;
    const todayKey = SCHEDULE_DAY_KEYS[new Date().getDay()];
    const blocks = this.blocksFor(profile, todayKey);
    const now = new Date();
    const nowMin = now.getHours() * 60 + now.getMinutes();
    const toMin = (hhmm) => { const [h, m] = hhmm.split(":").map(Number); return h * 60 + m; };

    document.querySelectorAll("#schedule-today-list .schedule-block").forEach((el) => {
      const b = blocks[parseInt(el.dataset.i)];
      if (!b) return;
      const start = toMin(b.s), end = toMin(b.e);
      el.classList.toggle("now", nowMin >= start && nowMin < end);
      el.classList.toggle("past", nowMin >= end);
    });

    if (typeof ContextBus !== "undefined") {
      const current = blocks.find(b => nowMin >= toMin(b.s) && nowMin < toMin(b.e));
      ContextBus.patch({ currentScheduleBlock: current ? current.t : null });
    }
  },

